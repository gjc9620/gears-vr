inline bool grip(vr::Vector contact,vr::Vector forward,vr::Vector stem,
    vr::Vector grip_to_wrist_m,vr::Quaternion grip_to_wrist,double units,double model_scale,vr::Pose& out) noexcept {
    if(!vr::finite(contact)||!g::normalize(forward)||!g::normalize(stem)||
       !vr::finite(grip_to_wrist_m)||!g::rotation_valid(grip_to_wrist)||
       !std::isfinite(units)||units<10||units>500||!std::isfinite(model_scale)||
       model_scale<=0||std::abs(model_scale*100/units-1.)>.001)return false;
    stem=g::sub(stem,g::scale(forward,g::dot(stem,forward)));
    if(!g::normalize(stem))return false;
    const auto x=g::scale(forward,-1.);
    const vr::Vector y{forward.y*stem.z-forward.z*stem.y,
                       forward.z*stem.x-forward.x*stem.z,
                       forward.x*stem.y-forward.y*stem.x};
    const vr::Matrix basis{{{x.x,y.x,stem.x},{x.y,y.y,stem.y},{x.z,y.z,stem.z}}};
    vr::Quaternion wrist{};
    if(!vr::rig_tracking::detail::quaternion(basis,wrist)||!g::rotation_valid(wrist))return false;
    const auto rotation=vr::normalized(vr::multiply(wrist,vr::inverse(grip_to_wrist)));
    const auto palm=vr::transform(vr::rotation_matrix(wrist),g::scale(contact_in_wrist_m,units));
    const auto offset=vr::transform(vr::rotation_matrix(rotation),g::scale(grip_to_wrist_m,units));
    const vr::Pose candidate{g::sub(g::sub(contact,palm),offset),rotation};
    if(!vr::finite(candidate.position)||!g::rotation_valid(candidate.orientation))return false;
    out=candidate;return true;
}
