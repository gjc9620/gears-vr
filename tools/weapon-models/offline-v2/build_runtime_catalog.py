"""Compile the public asset-input manifest into bounded runtime metadata only."""
from pathlib import Path
import hashlib
import json

ROOT=Path(__file__).resolve().parents[3]
INPUT=ROOT/'assets/weapon-6dof/offline-v2/engine-input'
OUTPUT=ROOT/'tools/vr-common/weapon_part_input_catalog.h'

def generate():
    manifest=json.loads((INPUT/'manifest.json').read_text(encoding='utf-8'))
    if manifest['schema']!='gearsvr.offline-engine-input.v2' or manifest['record_stride']!=60:
        raise ValueError('Unsupported asset input schema')
    lines=['#pragma once','#include "weapon_part_geometry.h"',
           '// Generated by tools/weapon-models/offline-v2/build_runtime_catalog.py.',
           '// Public authored geometry metadata only; no game-derived model data.',
           'namespace gears_weapon::part_input_catalog {',
           'struct Asset {const char* id;const wchar_t* vertex_file;const wchar_t* index_file;',
           'std::size_t vertices,indices;std::array<std::uint8_t,32> vertex_hash,index_hash;',
           'const part_geometry::Section* sections;std::size_t section_count;};']
    entries=[];seen=set()
    for index,asset in enumerate(manifest['assets']):
        vertex=asset['vertex_file'];indices=asset['index_file'];name=Path(vertex).stem
        if name in seen or Path(vertex).name!=vertex or Path(indices).name!=indices:
            raise ValueError('Duplicate/unsafe input name')
        seen.add(name)
        for file,key in [(vertex,'vertex_sha256'),(indices,'index_sha256')]:
            if hashlib.sha256((INPUT/file).read_bytes()).hexdigest()!=asset[key]:
                raise ValueError('Input digest mismatch: '+file)
        section_name='sections_'+str(index)
        sections=','.join('{'+','.join(str(s[k]) for k in
            ['material_index','first_index','triangles','min_vertex','max_vertex'])+'}' for s in asset['sections'])
        lines.append('inline constexpr part_geometry::Section '+section_name+'[]={'+sections+'};')
        digest=lambda key:'{'+','.join('0x'+asset[key][i:i+2] for i in range(0,64,2))+'}'
        entries.append('{'+json.dumps(name)+',L'+json.dumps(vertex)+',L'+json.dumps(indices)+','+
            str(asset['vertices'])+','+str(asset['triangles']*3)+','+
            digest('vertex_sha256')+','+digest('index_sha256')+','+section_name+',std::size('+section_name+')},')
    lines.extend(['inline constexpr Asset assets[]={',*entries,'};','}'])
    OUTPUT.write_text('\n'.join(lines)+'\n',encoding='utf-8')
    return {'assets':len(entries),'game_derived_payload':False,'output':str(OUTPUT)}

if __name__=='__main__':
    print(json.dumps(generate()))
